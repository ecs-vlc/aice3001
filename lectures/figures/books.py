"""Data for books.asy: rank-3 SVD and non-negative factorisations of a
words x books count matrix.  Writes books_data.asy.  Replaces books.m.
Run:  python books.py && asy books.asy
"""
import numpy as np

M = np.array([[51, 101, 5, 10, 3, 1], [51, 103, 2, 8, 0, 0],
              [22, 51, 60, 72, 5, 7], [0, 70, 90, 50, 3, 3],
              [0, 1, 51, 92, 2, 0], [0, 4, 5, 1, 161, 89],
              [0, 1, 3, 1, 35, 2]], float)
K = 3

# best rank-3 approximation; A = first K columns of U S, B = first K rows
# of V^T, scaled by 10 to make the numbers readable.  Signs are fixed so
# each column of A has a positive sum (the SVD only fixes them up to sign).
U, s, Vt = np.linalg.svd(M, full_matrices=False)
A, B = U[:, :K] * s[:K] / 10, 10 * Vt[:K]
sign = np.sign(A.sum(0))
A, B = A * sign, B * sign[:, None]

# NMF by Lee & Seung's multiplicative updates, from a fixed random start
rng = np.random.default_rng(0)
A1, B1 = rng.random((M.shape[0], K)) + 0.1, rng.random((K, M.shape[1])) + 0.1
for _ in range(5000):
    B1 *= (A1.T @ M) / (A1.T @ A1 @ B1 + 1e-12)
    A1 *= (M @ B1.T) / (A1 @ B1 @ B1.T + 1e-12)
# NMF is unique only up to scaling: put the scale into A1 (as for the SVD)
scale = B1.max(1) / 10
A1, B1 = A1 * scale, B1 / scale[:, None]
order = np.argsort(-A1.sum(0))
A1, B1 = A1[:, order], B1[order]

rel = lambda X, Y: np.linalg.norm(M - X @ Y) / np.linalg.norm(M)
print(f"relative error: SVD {rel(A, B):.3f}, NMF {rel(A1, B1):.3f}")


def arr(X):
    return "{" + ",".join("{" + ",".join(f"{v:.6f}" for v in r) + "}" for r in X) + "}"


with open("books_data.asy", "w") as f:
    f.write("// generated by books.py -- do not edit\n")
    for name, X in [("A", A), ("B", B), ("A1", A1), ("B1", B1)]:
        f.write(f"real[][] {name} = {arr(X)};\n")
