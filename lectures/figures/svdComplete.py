"""Data for svdComplete.asy: matrix completion by iterated truncated SVD.

A 6x8 "ratings" matrix with rank-2 structure (users mix two tastes, films
lean to one of two genres) plus a little noise; about a quarter of the
entries are hidden.  Missing entries start at the user's mean rating; each
iteration takes the best rank-2 approximation (truncated SVD) and copies
its values into the missing entries only.  Writes svdComplete_data.asy.
Run:  python svdComplete.py && asy svdComplete.asy
"""
import numpy as np

SEED, K, ITERS = 30, 2, 4          # seed chosen for a clear rank-2 example
rng = np.random.default_rng(SEED)
m, n = 6, 8
taste = rng.random((m, 1))
U = np.hstack([taste, 1 - taste])
genre = rng.random(n) < 0.5
F = np.vstack([np.where(genre, 0.9, 0.1), np.where(genre, 0.1, 0.9)]) \
    + 0.1 * rng.random((2, n))
T = np.clip(np.round(1 + 4 * (U @ F) + 0.15 * rng.standard_normal((m, n)), 1), 1, 5)
W = rng.random((m, n)) > 0.25                     # True where observed


def rms_missing(X):
    return np.sqrt(np.mean((X - T)[~W] ** 2))


mu = np.array([T[i, W[i]].mean() for i in range(m)])[:, None]
X = np.where(W, T, mu)
frames = [("fill", X.copy(), rms_missing(X))]
for t in range(ITERS):
    u, s, vt = np.linalg.svd(X)
    L = (u[:, :K] * s[:K]) @ vt[:K]
    frames.append(("lowrank", L.copy(), rms_missing(np.where(W, T, L))))
    X = np.where(W, T, L)
    frames.append(("fill", X.copy(), rms_missing(X)))


def arr(A):
    return "{" + ",".join("{" + ",".join(f"{v:.4f}" for v in row) + "}" for row in A) + "}"


with open("svdComplete_data.asy", "w") as f:
    f.write("// generated by svdComplete.py -- do not edit\n")
    f.write(f"real[][] T = {arr(T)};\n")
    f.write("bool[][] W = {" + ",".join("{" + ",".join("true" if w else "false" for w in row) + "}" for row in W) + "};\n")
    f.write("string[] kind = {" + ",".join(f'"{k}"' for k, _, _ in frames) + "};\n")
    f.write("real[][][] F = {" + ",".join(arr(A) for _, A, _ in frames) + "};\n")
    f.write("real[] err = {" + ",".join(f"{e:.4f}" for _, _, e in frames) + "};\n")
print("hidden entries:", (~W).sum(), " rms on hidden:", [round(e, 2) for _, _, e in frames])
print("singular values of the full matrix:", np.round(np.linalg.svd(T, compute_uv=False), 2))
