"""Data for errorbarsT.asy: p-value of a two-sample t-test against the
number of samples n per group, when two means with equal standard errors
Delta are a given gap apart.  The standard error of the difference is
sqrt(2) Delta, so t = gap/(sqrt(2) Delta), with 2(n-1) degrees of freedom.
Writes errorbarsT_data.asy.  Run:  python errorbarsT.py && asy errorbarsT.asy
"""
import numpy as np
from scipy.stats import norm, t as tdist

gaps = [2.0, 1.96 * np.sqrt(2)]          # bars touching; just significant
ns = np.unique(np.round(np.logspace(np.log10(2), 6, 200)).astype(int))
with open("errorbarsT_data.asy", "w") as f:
    f.write("// generated by errorbarsT.py -- do not edit\n")
    f.write("real[] gaps = {" + ",".join(f"{g:.6f}" for g in gaps) + "};\n")
    f.write("real[] ns = {" + ",".join(str(n) for n in ns) + "};\n")
    rows = []
    for g in gaps:
        t = g / np.sqrt(2)
        p = 2 * tdist.sf(t, 2 * (ns - 1))
        rows.append("{" + ",".join(f"{v:.6f}" for v in p) + "}")
        print(f"gap {g:.3f} Delta: t = {t:.3f}, p(n=2) = {p[0]:.3f}, "
              f"p(n=10) = {p[np.searchsorted(ns, 10)]:.3f}, large n -> {2*norm.sf(t):.4f}")
    f.write("real[][] pv = {" + ",".join(rows) + "};\n")
